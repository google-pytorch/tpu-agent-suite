"""Runs hardware probes on the compute target and keeps what they print.

A hardware probe answers one question about the TPU or the Pallas/Mosaic
toolchain in front of the loop -- does this construct lower, how much VMEM can
a kernel really use, what does a grid step cost -- by measuring it on the
target. The probes live in `hw_probes/checks/`; the hardware probe catalog
lists every one with the design question it answers. They never time the
kernel itself: the test harness does that.

    hw_probe.py list [--group partitioning]
    hw_probe.py build --pick vmem_scratch_bisect [--pick dispatch_floor] \
        [--refresh <name>] --work <work> --output <work>/hw_probes/job.py
    hw_probe.py record --stdout <work>/hw_probes/job.out --work <work>

`list` runs where the loop runs and never touches a device. `build` answers
what it can from the cache and writes one self-contained script (the probe
harness plus the needed `checks/` modules, inlined as text) that `compute run`
executes on the target. `record` reads that job's stdout.

Every job also runs `software_versions` and `device_inventory`, and its
results are cached under `<work>/hw_probes/cache/<device>/<versions>/`, keyed
by what those two report. `build` runs where no TPU is, so it serves the
cache of the environment this slot saw last; that is why a job always goes
out, with only the two stamp probes when everything was cached. `record`
checks the served answers against the stamp the job reports and removes
them as STALE on a mismatch, so a number measured on one environment is
never kept for another. Each answer is also written to
`<work>/hw_probes/<name>.txt`, the file a plan cites.

Only PASS and UNSUPPORTED are cached: they are a property of the device and
toolchain. A FAIL can be an error from a busy or wedged TPU and an INVALID a
noisy run, so both are filed for the plan in hand and re-measured the next
time one is asked for. `--refresh <name>` re-measures one cached answer.

Destructive probes can halt the Mosaic core and poison later jobs on the same
TPU, so `build` refuses them unless `--allow-destructive` is passed. Agents
never pass it.
"""

import argparse
import contextlib
import io
import json
import os
import re
import sys
from typing import Any

_HERE = os.path.dirname(os.path.abspath(__file__))
PROBES_DIR = os.path.join(_HERE, "hw_probes")

# Always run alongside the requested probes, so every output says which
# device and toolchain produced it. Their output is the cache key.
STAMP_PROBES = ("software_versions", "device_inventory")
_STAMP_MODULE = "checks.environment"
# Only these are a property of the device and toolchain. A FAIL can be an
# error from a busy or wedged TPU and an INVALID a noisy run, so caching
# either would serve a one-off as a fact.
CACHED_VERDICTS = ("PASS", "UNSUPPORTED")
_TAIL_CHARS = 4000
_PROGRESS = re.compile(r"^ {6}[.>] ")

_SCRIPT_TEMPLATE = """\
# Generated by hw_probe.py. Self-contained: the probe harness and the needed
# checks/ modules are inlined below and written to a scratch directory before
# they are imported.
import os
import sys
import tempfile

FILES = {files!r}

_root = tempfile.mkdtemp(prefix="hw_probes_")
for _rel, _src in FILES.items():
    _path = os.path.join(_root, _rel)
    os.makedirs(os.path.dirname(_path), exist_ok=True)
    with open(_path, "w") as _f:
        _f.write(_src)

sys.path.insert(0, _root)
sys.stdout.reconfigure(line_buffering=True)

import run_probes  # noqa: E402

run_probes.main({argv!r})
# FAIL is a finding, not an infrastructure error: always exit 0 so the
# caller reads the output.
sys.exit(0)
"""


def _registry() -> list[Any]:
    """Every registered probe, imported where the loop runs.

    The check modules import jax inside their probe bodies only, so this
    needs the standard library and nothing else.
    """
    if PROBES_DIR not in sys.path:
        sys.path.insert(0, PROBES_DIR)
    import harness  # pylint: disable=import-outside-toplevel
    import run_probes  # pylint: disable=import-outside-toplevel
    with contextlib.redirect_stdout(io.StringIO()):
        run_probes._import_all_check_modules()  # pylint: disable=protected-access
    return list(harness.registered_probes())


def _module_of(probe: Any) -> str:
    """`checks.partitioning` for a probe registered in checks/partitioning.py."""
    return probe.body.__module__


def _read(path: str) -> str:
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def _probe_dir(work: str) -> str:
    return os.path.join(work, "hw_probes")


def _cache_dir(work: str) -> str:
    return os.path.join(_probe_dir(work), "cache")


def _last_stamp_file(work: str) -> str:
    return os.path.join(_cache_dir(work), "last_stamp.txt")


def _pending_file(work: str) -> str:
    return os.path.join(_probe_dir(work), "pending.json")


# ---------------------------------------------------------------------------
# Parsing a job's output
# ---------------------------------------------------------------------------


def stamp_key(output: str) -> str | None:
    """The cache key, from the stamp probes' detail strings."""
    versions = re.search(r"software_versions\n.*\n\s+PASS[^:]*:\s*(.+)",
                         output)
    devices = re.search(r"device_inventory\n.*\n\s+PASS[^:]*:\s*(.+)", output)
    if not versions or not devices:
        return None
    kinds = re.search(r"kinds=\[([^\]]*)\]", devices.group(1))
    device = (kinds.group(1) if kinds else "unknown").strip("'\" ")
    wanted = {}
    for item in versions.group(1).split():
        name, _, value = item.partition("=")
        if name in ("jax", "jaxlib", "libtpu"):
            wanted[name] = value
    version_key = "-".join(f"{name}{wanted.get(name, 'absent')}"
                           for name in ("jax", "jaxlib", "libtpu"))

    def safe(text: str) -> str:
        return re.sub(r"[^A-Za-z0-9._-]+", "_", text)

    return f"{safe(device)}/{safe(version_key)}"


def split_by_probe(output: str) -> dict[str, str]:
    """Cuts each probe's report out of the combined output.

    A report is a `[group] name` header, the question, and the verdict line,
    whose detail string may run over several lines. It ends at the next
    report header or at the suite's closing `====` rule. Progress lines a
    probe prints while it runs (`      . <arm> ...`, `      > starting ...`)
    come before its own report, so any trailing the previous report belong
    to the next probe and are dropped.
    """
    blocks = {}
    for header in re.finditer(r"\n\[[^\]\n]+\] ([A-Za-z0-9_]+)\n", output):
        name = header.group(1)
        ends = [
            pos for pos in (
                output.find("\n\n[", header.end()),
                output.find("\n" + "=" * 20, header.end()),
            ) if pos != -1
        ]
        end = min(ends) if ends else len(output)
        lines = output[header.start() + 1:end].strip("\n").split("\n")
        while len(lines) > 3 and _PROGRESS.match(lines[-1]):
            lines.pop()
        blocks.setdefault(name, "\n".join(lines))
    return blocks


def verdict_of(block: str) -> str | None:
    """PASS, FAIL, UNSUPPORTED, INVALID or SKIPPED, from a report block."""
    match = re.search(r"^\s+(PASS|FAIL|UNSUPPORTED|INVALID|SKIPPED) \(", block,
                      re.MULTILINE)
    return match.group(1) if match else None


# ---------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------


def cmd_list(groups: list[str]) -> int:
    for probe in _registry():
        if groups and probe.group not in groups:
            continue
        flag = " [destructive]" if probe.destructive else ""
        print(f"{probe.group:<14} {probe.name}{flag}")
        print(f"    {probe.question}")
    return 0


def _cached(work: str, names: list[str]) -> tuple[str | None, dict[str, str]]:
    """The last stamp seen in this slot, and the results cached under it."""
    key_file = _last_stamp_file(work)
    if not os.path.exists(key_file):
        return None, {}
    stamp = _read(key_file).strip()
    found = {}
    for name in names:
        path = os.path.join(_cache_dir(work), stamp, f"{name}.txt")
        if os.path.exists(path):
            found[name] = _read(path)
    return stamp, found


def _write_answer(work: str, name: str, stamp: str | None, block: str) -> str:
    path = os.path.join(_probe_dir(work), f"{name}.txt")
    _write(path, f"environment: {stamp or 'unknown'}\n{block.rstrip()}\n")
    return path


_CHECK_IMPORT_RE = re.compile(r"^\s*(?:from|import)\s+(checks\.[a-z0-9_]+)",
                              re.MULTILINE)


def with_dependencies(modules: set[str]) -> set[str]:
    """`modules` plus every check module they import, transitively.

    A check module may borrow helpers from another (`sparsecore_gaps` imports
    from `sparsecore`). The runner imports every module the job carries, so
    a job that carries one without the other fails before any probe runs.
    """
    found = set(modules)
    pending = list(modules)
    while pending:
        rel = pending.pop().replace(".", "/") + ".py"
        for imported in _CHECK_IMPORT_RE.findall(
                _read(os.path.join(PROBES_DIR, rel))):
            if imported not in found:
                found.add(imported)
                pending.append(imported)
    return found


def build_script(names: list[str], modules: set[str],
                 allow_destructive: bool) -> str:
    """One script that runs `names` on the target and prints their reports."""
    files = {
        "harness.py":
        _read(os.path.join(PROBES_DIR, "harness.py")),
        "run_probes.py":
        _read(os.path.join(PROBES_DIR, "run_probes.py")),
        "checks/__init__.py":
        _read(os.path.join(PROBES_DIR, "checks", "__init__.py")),
    }
    for module in sorted(with_dependencies(modules)):
        rel = module.replace(".", "/") + ".py"
        files[rel] = _read(os.path.join(PROBES_DIR, rel))
    argv = ["--traceback"]
    for name in names:
        argv += ["--pick", name]
    if allow_destructive:
        argv.append("--include-destructive")
    return _SCRIPT_TEMPLATE.format(files=files, argv=argv)


def cmd_build(args: argparse.Namespace) -> int:
    probes = {probe.name: probe for probe in _registry()}
    picks = list(dict.fromkeys(args.pick + args.refresh))
    if not picks:
        print("name at least one probe with --pick or --refresh.",
              file=sys.stderr)
        return 2
    unknown = [name for name in picks if name not in probes]
    if unknown:
        print(
            f"unknown probe name(s): {', '.join(unknown)}. Names are exact; "
            "see `list` or the hardware probe catalog.",
            file=sys.stderr)
        return 2
    destructive = [name for name in picks if probes[name].destructive]
    if destructive and not args.allow_destructive:
        print(
            f"refusing destructive probe(s): {', '.join(destructive)}. They "
            "can halt the Mosaic core and break later jobs on this TPU.",
            file=sys.stderr)
        return 2

    refresh = set(args.refresh)
    stamp, cached = ((None, {}) if args.no_cache else _cached(
        args.work, [name for name in picks if name not in refresh]))
    for name, block in cached.items():
        path = _write_answer(args.work, name, stamp, block)
        print(f"CACHED: {name} -> {path}")
    todo = [name for name in picks if name not in cached]

    # The cache is looked up under the stamp this slot saw last, but only the
    # target knows which device and toolchain it is now. So a job always
    # goes out, if only with the two stamp probes, and `record` checks the
    # answers served above against the stamp it reports.
    names = list(STAMP_PROBES) + [n for n in todo if n not in STAMP_PROBES]
    modules = {_STAMP_MODULE} | {_module_of(probes[n]) for n in todo}
    _write(args.output, build_script(names, modules, args.allow_destructive))
    _write(
        _pending_file(args.work),
        json.dumps(
            {
                "picks": todo,
                "served": sorted(cached),
                "served_stamp": stamp,
                "no_cache": args.no_cache
            },
            indent=2) + "\n")
    if todo:
        print(f"JOB: {args.output} -- runs {', '.join(todo)}.")
    else:
        print(f"JOB: {args.output} -- every answer was cached; this job runs "
              "only the stamp probes, which confirm the cached answers were "
              "measured on this target.")
    return 0


def cmd_record(args: argparse.Namespace) -> int:
    output = _read(args.stdout)
    pending: dict[str, Any] = {}
    if os.path.exists(_pending_file(args.work)):
        pending = json.loads(_read(_pending_file(args.work)))
    picks = pending.get("picks", [])
    no_cache = bool(pending.get("no_cache"))

    if "probe suite:" not in output or "probe suite: 0 of" in output:
        print(output[-_TAIL_CHARS:])
        print(
            "the job did not run any probe; see its output above. Nothing "
            "was recorded.",
            file=sys.stderr)
        return 1

    stamp = stamp_key(output)
    if stamp is None:
        # Without the stamp nothing says which device or toolchain answered,
        # and the usual cause is a job that never reached the device (busy,
        # wedged, no backend): every probe then FAILs on the same error,
        # which reads as a finding. File none of it.
        print(output[-_TAIL_CHARS:])
        print(
            "software_versions or device_inventory did not PASS, so this "
            "output cannot be tied to a device and toolchain; see the output "
            "above. Nothing was recorded. Fix what stopped the job and run "
            "it again.",
            file=sys.stderr)
        return 1

    blocks = split_by_probe(output)
    for name, block in blocks.items():
        verdict = verdict_of(block)
        cache_path = os.path.join(_cache_dir(args.work), stamp, f"{name}.txt")
        note = ""
        if no_cache:
            pass
        elif verdict in CACHED_VERDICTS:
            _write(cache_path, block + "\n")
        else:
            # A FAIL may be a hiccup on a shared TPU and an INVALID a noisy
            # run: file them for this plan, but never serve them later. Drop
            # any older answer under this stamp, so a probe re-run with
            # --refresh does not leave the answer it replaced behind.
            if os.path.exists(cache_path):
                os.remove(cache_path)
            note = " (not cached)"
        path = _write_answer(args.work, name, stamp, block)
        print(f"{verdict or 'NO VERDICT'}: {name} -> {path}{note}")
    if not no_cache:
        _write(_last_stamp_file(args.work), stamp + "\n")
    print(f"environment: {stamp}")

    failed = False
    served = pending.get("served", [])
    served_stamp = pending.get("served_stamp")
    if served and served_stamp != stamp:
        # The answers `build` served came from the cache of another device or
        # toolchain. They are not answers for this target: unfile them.
        for name in served:
            answer = os.path.join(_probe_dir(args.work), f"{name}.txt")
            if os.path.exists(answer):
                os.remove(answer)
            print(f"STALE: {name} -- cached on {served_stamp}, this target is "
                  f"{stamp}; its answer was removed")
        print(
            f"cached answers for another environment: {', '.join(served)}. "
            "Run build again: they are now cache misses and the new job "
            "measures them here.",
            file=sys.stderr)
        failed = True

    missing = [name for name in picks if name not in blocks]
    if missing:
        print(output[-_TAIL_CHARS:])
        print(
            f"no result for: {', '.join(missing)}. The job may have died "
            "mid-run; the output above ends where it stopped.",
            file=sys.stderr)
        failed = True
    if failed:
        return 1
    if os.path.exists(_pending_file(args.work)):
        os.remove(_pending_file(args.work))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("list", help="Print the registry; touches no device")
    p.add_argument("--group",
                   action="append",
                   default=[],
                   help="only this group; repeatable")

    p = sub.add_parser("build", help="Serve the cache; write the job script")
    p.add_argument("--pick",
                   action="append",
                   default=[],
                   help="a probe's exact name; repeatable")
    p.add_argument("--refresh",
                   action="append",
                   default=[],
                   help="a probe to re-measure even if it is cached; its "
                   "new answer replaces the cached one. Repeatable")
    p.add_argument("--work", required=True, help="this kernel's slot")
    p.add_argument("--output",
                   required=True,
                   help="where to write the job script")
    p.add_argument("--no-cache",
                   action="store_true",
                   help="ignore the cache and do not write it")
    p.add_argument("--allow-destructive",
                   action="store_true",
                   help="permit probes that can halt the TPU core; never "
                   "passed by an agent")

    p = sub.add_parser("record", help="Cache and file a finished job")
    p.add_argument("--stdout",
                   required=True,
                   help="the job's saved stdout, verbatim")
    p.add_argument("--work", required=True, help="this kernel's slot")

    args = parser.parse_args(argv)
    if args.cmd == "list":
        return cmd_list(args.group)
    if args.cmd == "build":
        return cmd_build(args)
    return cmd_record(args)


if __name__ == "__main__":
    sys.exit(main())
